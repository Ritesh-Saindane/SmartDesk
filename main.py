class Task(BaseModel):
    id: str = Field(..., description="Unique task ID generated by Python.")
    agent: Literal["WorkspaceAgent", "KnowledgeAgent", "ProductivityAgent"]
    instruction: str
    context_artifacts: List[str] = Field(default_factory=list)
    expected_output: str
    status: str = "pending"

class Artifact(BaseModel):
    id: str
    type: str
    title: str
    description: str
    metadata: Dict[str, Any] = Field(default_factory=dict)
    payload: Any = None

class OrchestratorTask(BaseModel):
    agent: Literal["WorkspaceAgent", "KnowledgeAgent", "ProductivityAgent"]
    instruction: str
    context_artifacts: List[str] = Field(default_factory=list)
    expected_output: str

class OrchestratorDecision(BaseModel):
    finished: bool = Field(..., description="True if the user query is fully resolved.")
    task: Optional[OrchestratorTask] = Field(None, description="The single next task to assign.")
    final_response: Optional[str] = Field(None, description="Final message to user when finished.")

