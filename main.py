def build_graph():
    builder = StateGraph(GraphState)

    # ── Nodes ────────────────────────────────────────────
    builder.add_node("Orchestrator",        orchestrator)

    builder.add_node("WorkspaceAgent",      workspace_agent)
    builder.add_node("WorkspaceToolNode",   workspace_tool_node)
    builder.add_node("WorkspaceFinalizer",  workspace_finalizer)

    builder.add_node("KnowledgeAgent",      knowledge_agent)
    builder.add_node("KnowledgeToolNode",   knowledge_tool_node)
    builder.add_node("KnowledgeFinalizer",  knowledge_finalizer)

    builder.add_node("ProductivityAgent",      productivity_agent)
    builder.add_node("ProductivityToolNode",   productivity_tool_node)
    builder.add_node("ProductivityFinalizer",  productivity_finalizer)

    # ── Entry ─────────────────────────────────────────────
    builder.add_edge(START, "Orchestrator")

    # ── Orchestrator routes to one agent (or END) ─────────
    builder.add_conditional_edges("Orchestrator", orchestrator_route)

    # ── WorkspaceAgent mini-loop ──────────────────────────
    builder.add_conditional_edges("WorkspaceAgent",   workspace_route)
    builder.add_edge("WorkspaceToolNode",  "WorkspaceAgent")   # loop back for more calls
    builder.add_edge("WorkspaceFinalizer", "Orchestrator")

    # ── KnowledgeAgent mini-loop ──────────────────────────
    builder.add_conditional_edges("KnowledgeAgent",   knowledge_route)
    builder.add_edge("KnowledgeToolNode",  "KnowledgeAgent")   # loop back for more calls
    builder.add_edge("KnowledgeFinalizer", "Orchestrator")

    # ── ProductivityAgent mini-loop ───────────────────────
    builder.add_conditional_edges("ProductivityAgent",   productivity_route)
    builder.add_edge("ProductivityToolNode",  "ProductivityAgent")  # loop back for more calls
    builder.add_edge("ProductivityFinalizer", "Orchestrator")

    return builder.compile()


